package tn3270

// Buffer addresses in the 3270 data stream are two bytes.  12-bit addresses
// carry six bits per byte, each mapped through addrCodes so that the byte is
// a printable EBCDIC graphic; 14-bit addresses are binary with the top two
// bits of the first byte zero.  The two bits 0xC0 of the first byte tell them
// apart on input.  A 24x80 screen (1920 positions) always fits in 12 bits,
// and that is what a 3278-2 sends.

var addrCodes = [64]byte{
	0x40, 0xC1, 0xC2, 0xC3, 0xC4, 0xC5, 0xC6, 0xC7, 0xC8, 0xC9, 0x4A, 0x4B, 0x4C, 0x4D, 0x4E, 0x4F,
	0x50, 0xD1, 0xD2, 0xD3, 0xD4, 0xD5, 0xD6, 0xD7, 0xD8, 0xD9, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F,
	0x60, 0x61, 0xE2, 0xE3, 0xE4, 0xE5, 0xE6, 0xE7, 0xE8, 0xE9, 0x6A, 0x6B, 0x6C, 0x6D, 0x6E, 0x6F,
	0xF0, 0xF1, 0xF2, 0xF3, 0xF4, 0xF5, 0xF6, 0xF7, 0xF8, 0xF9, 0x7A, 0x7B, 0x7C, 0x7D, 0x7E, 0x7F,
}

// decodeAddr reads a 12- or 14-bit buffer address.
func decodeAddr(b1, b2 byte) int {
	if b1&0xC0 == 0 { // 14-bit binary
		return int(b1&0x3F)<<8 | int(b2)
	}
	return int(b1&0x3F)<<6 | int(b2&0x3F)
}

// encodeAddr writes a buffer address: 12-bit coded below 4096, 14-bit binary
// above (up to 16383).
func encodeAddr(a int) (byte, byte) {
	if a < 4096 {
		return addrCodes[(a>>6)&0x3F], addrCodes[a&0x3F]
	}
	return byte((a >> 8) & 0x3F), byte(a)
}
